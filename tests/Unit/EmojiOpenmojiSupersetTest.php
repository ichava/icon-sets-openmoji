<?php

declare(strict_types=1);

/*
|--------------------------------------------------------------------------
| This pack holds everything icon-sets-emoji's OpenMoji sets held
|--------------------------------------------------------------------------
|
| icon-sets-emoji shipped copies of openmoji-color and openmoji-black until
| they were removed there (owner, 2026-11-05). Before removing them, the claim
| that nothing is lost had to be checked rather than asserted:
| tests/fixtures/emoji-openmoji-manifest.txt lists every one of those SVGs,
| with the first 16 hex characters of its sha256, as icon-sets-emoji held them
| at the commit named in the file's header. Generated by walking
| icon-sets-emoji's resources/assets/svg/files/openmoji-{color,black}.
|
| Every entry must exist here at the same set and item path, byte for byte.
| A file that moved category would fail the path check and show up by name.
|
*/

function openmoji_files_root(): string
{
    return dirname(__DIR__, 2) . '/resources/assets/svg/files';
}

it(description: 'holds every OpenMoji SVG icon-sets-emoji shipped, at the same path and bytes', closure: function () {
    $manifest = file(dirname(__DIR__) . '/fixtures/emoji-openmoji-manifest.txt', FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES);
    $entries = array_values(array_filter((array) $manifest, static fn (string $line): bool => ! str_starts_with($line, '#')));

    // 3,567 per set. A manifest that stopped matching would otherwise pass.
    expect($entries)->toHaveCount(7134);

    $missing = [];
    $changed = [];

    foreach ($entries as $entry) {
        [$path, $hash] = explode(' ', $entry, 2);
        $file = openmoji_files_root() . '/' . $path;

        if (! is_file($file)) {
            $missing[] = $path;

            continue;
        }

        if (substr(hash_file('sha256', $file), 0, 16) !== $hash) {
            $changed[] = $path;
        }
    }

    expect($missing)->toBe([], 'missing here: ' . implode(', ', array_slice($missing, 0, 10)))
        ->and($changed)->toBe([], 'bytes differ: ' . implode(', ', array_slice($changed, 0, 10)));
});

it(description: 'holds OpenMoji art only: two OpenMoji sets, every file on its 72x72 canvas', closure: function () {
    $sets = array_values(array_filter(
        (array) scandir(openmoji_files_root()),
        static fn (string $entry): bool => $entry[0] !== '.' && is_dir(openmoji_files_root() . '/' . $entry),
    ));

    expect($sets)->toBe(['openmoji-black', 'openmoji-color']);

    $files = new RecursiveIteratorIterator(new RecursiveDirectoryIterator(openmoji_files_root(), FilesystemIterator::SKIP_DOTS));
    $inspected = 0;
    $foreign = [];

    foreach ($files as $file) {
        if (! $file instanceof SplFileInfo || $file->getExtension() !== 'svg') {
            continue;
        }

        $inspected++;
        $svg = (string) file_get_contents($file->getPathname());

        // Every OpenMoji SVG is drawn on a 72x72 canvas inside a group with
        // id="emoji"; Twemoji's is 36x36.
        if (! str_contains($svg, 'viewBox="0 0 72 72"') || ! str_contains($svg, 'id="emoji"')) {
            $foreign[] = $file->getPathname();
        }
    }

    expect($inspected)->toBeGreaterThanOrEqual(8000)
        ->and($foreign)->toBe([], 'not OpenMoji: ' . implode(', ', array_slice($foreign, 0, 10)));
});
